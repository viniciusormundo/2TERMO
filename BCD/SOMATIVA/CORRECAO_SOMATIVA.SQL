-- CORREÇÃO SOMATIVA 01 -- OFICINA MECANICA

CREATE DATABASE IF NOT EXISTS OFICINA_MECANICA;
USE OFICINA_MECANICA;

CREATE TABLE IF NOT EXISTS CLIENTES (
    ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    NOME_CLIENTE VARCHAR(60) NOT NULL,
    TELEFONE CHAR(15) NOT NULL ,
    EMAIL VARCHAR(100) NOT NULL,
    CPF CHAR(14) NOT NULL UNIQUE,
    DATA_NASCIMENTO DATE NOT NULL,
    STATUS_CLIENTE ENUM('ATIVO', 'INATIVO') DEFAULT 'ATIVO',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS VEICULOS (
    ID_VEICULO INT AUTO_INCREMENT PRIMARY KEY,
    PLACA CHAR(7) NOT NULL UNIQUE,
    TIPO_VEICULO ENUM('CARRO', 'MOTO', 'BIKE') DEFAULT 'CARRO' NOT NULL,
    COR CHAR(20),
    QUILOMETRAGEM FLOAT,
    TIPO_MOTOR ENUM ('ELETRICO', 'COMBUSATÃO'),
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF  NOT EXISTS MARCA (
    ID_MARCA INT AUTO_INCREMENT PRIMARY KEY,
    ANO_LANCAMENTO YEAR,
    PAIS_ORIGEM VARCHAR(60),
    STATUS_MARCA ENUM('ATIVA', 'INATIVA') DEFAULT 'ATIVA',
    NOME_MARCA VARCHAR(60) NOT NULL,
    SITE_MARCA VARCHAR(100),       
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP

);

CREATE TABLE IF NOT EXISTS MODELO (
    ID_MODELO INT AUTO_INCREMENT PRIMARY KEY,
    COR VARCHAR(20) NOT NULL,
    VALOR_MODELO DECIMAL(10,2) NOT NULL,
    CATEGORIA ENUM('SEDAN', 'HATCH', 'SUV'),
    NOME_MODELO VARCHAR(60),
    STATUS_MODELO ENUM('ATIVO', 'INATIVO') DEFAULT 'ATIVO',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS FUNCIONARIOS (
    ID_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_FUNCIONARIO VARCHAR(60) NOT NULL,
    TELEFONE CHAR(15) NOT NULL,
    CPF_FUNCIONARIO CHAR(14) NOT NULL UNIQUE,
    CARGO VARCHAR(60) NOT NULL,
    STATUS_FUNCIONARIO ENUM('ATIVO', 'INATIVO') DEFAULT 'ATIVO',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS SERVICOS (
    ID_SERVICO INT AUTO_INCREMENT PRIMARY KEY,
    TIPO_SERVICO VARCHAR(60) NOT NULL,
    DESCRICAO_SERVICO VARCHAR(100) NOT NULL,
    PRECO_SERVICO DECIMAL(10,2) DEFAULT 0.00 NOT NULL,
    DATA_INICIO DATETIME NOT NULL,
    DATA_TERMINO DATETIME NOT NULL,
    STATUS_SERVICO ENUM('PENDENTE', 'EM ANDAMENTO', 'CONCLUIDO') DEFAULT 'PENDENTE',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PECAS (
    ID_PECA INT AUTO_INCREMENT PRIMARY KEY,
    TAMANHO_PECA VARCHAR(20) NOT NULL,
    NOME_PECA VARCHAR(60) NOT NULL,
    DESCRICAO_PECA VARCHAR(100) NOT NULL,
    PRECO_PECA DECIMAL(10,2) DEFAULT 0.00 NOT NULL,
    STATUS_PECA ENUM('DISPONIVEL', 'INDISPONIVEL') DEFAULT 'DISPONIVEL',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ORDEM_SERVICO (
    ID_ORDEM_SERVICO INT AUTO_INCREMENT PRIMARY KEY,
    PRIORIDADE_SERVICO ENUM('URGENTE', 'SIMPLES') DEFAULT 'SIMPLES',
    PRAZO_FINAL DATE NOT NULL,
    RANKING_ORDEM VARCHAR(40) NOT NULL,
    DATA_EMISSAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    TIPO_CASO VARCHAR(250) NOT NULL,
    STATUS_SERVICO ENUM('PENDENTE', 'EM ANDAMENTO', 'CONCLUIDO') DEFAULT 'PENDENTE'
);

CREATE TABLE IF NOT EXISTS PAGAMENTO(
    
    ID_PAGAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    TIPO_PAGAMENTO ENUM('DINHEIRO', 'CARTÃO', 'PIX') DEFAULT 'PIX' NOT NULL,
    VALOR_PAGO DECIMAL(10,2) DEFAULT 0.00 NOT NULL,
    DATA_PAGAMENTO DATE NOT NULL,
    STATUS_PAGAMENTO ENUM('PENDENTE', 'PAGO') DEFAULT 'PENDENTE',
    COMPROVANTE INT,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS FORNECEDORES (
    ID_FORNECEDOR INT AUTO_INCREMENT PRIMARY KEY,
    RAZÃO_SOCIAL VARCHAR(60) NOT NULL,
    CNPJ CHAR(18) NOT NULL UNIQUE,
    TELEFONE_CONTATO CHAR(15) NOT NULL,
    EMAIL_CONTATO VARCHAR(100) NOT NULL,
    STATUS_FORNECEDOR ENUM('ATIVO', 'INATIVO') DEFAULT 'ATIVO',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

