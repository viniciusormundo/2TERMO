-- criar tabelas - usuario, livro, emprestimo.
DROP DATABASE IF EXISTS biblioteca_senai_vinicius;
CREATE DATABASE IF NOT EXISTS biblioteca_senai_vinicius;

USE biblioteca_senai_vinicius;

CREATE TABLE usuario (
    ID_USUARIO INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE livro (
    ID_LIVRO INT AUTO_INCREMENT,
    TITULO VARCHAR(200) NOT NULL,
    AUTOR VARCHAR(100) NOT NULL,
    ANO_PUBLICACAO INT,
    ISBN CHAR(20) NOT NULL UNIQUE,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0
    CHECK (QUANTIDADE_DISPONIVEL >= 0),
    CONSTRAINT PK_LIVRO PRIMARY KEY (ID_LIVRO),
    CONSTRAINT UQ_ISBN UNIQUE (ISBN)
);

CREATE TABLE IF NOT EXISTS emprestimo (
    ID_EMPRESTIMO INT AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERTO' CHECK
    (STATUS_EMPRESTIMO IN ('ABERTO', 'DEVOLVIDO', 'ATRASADO')),
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    CONSTRAINT PK_EMPRESTIMO PRIMARY KEY (ID_EMPRESTIMO),
    CONSTRAINT FK_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES
    USUARIO (ID_USUARIO) ON DELETE RESTRICT,
    CONSTRAINT FK_LIVRO FOREIGN KEY (ID_LIVRO) REFERENCES
    LIVRO (ID_LIVRO) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS categoria (
    ID_CATEGORIA INT AUTO_INCREMENT,
    NOME VARCHAR(80) NOT NULL UNIQUE,
    ID_LIVRO INT NOT NULL,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT FK_LIVRO_CATEGORIA FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO (ID_LIVRO)
);

CREATE TABLE IF NOT EXISTS forncedor (
    ID_FORNECEDOR INT AUTO_INCREMENT,
    CNPJ CHAR(20) NOT NULL UNIQUE,
    RAZAO_SOCIAL VARCHAR(80)NOT NULL,
    CONSTRAINT PK_FORNECEDOR PRIMARY KEY (ID_FORNECEDOR),
    CONSTRAINT UQ_CNPJ UNIQUE (CNPJ)
);

